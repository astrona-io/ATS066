#!/usr/bin/env bash
# Check: exactly one generated ConfigMap scout-config-<hash> exists in
# starfleet and it carries the overlay message.
set -uo pipefail

names="$(kubectl -n starfleet get configmaps -o json 2>/dev/null | jq -r '.items[] | select(.metadata.name | test("^scout-config-[a-z0-9]{10}$")) | .metadata.name')"
count="$(echo "$names" | grep -c . || true)"
if [ "$count" != "1" ]; then
  echo "FAIL: found $count ConfigMaps named scout-config-<hash>, expected 1 (generated by Kustomize)"
  exit 1
fi

message="$(kubectl -n starfleet get configmap "$names" -o json | jq -r '.data.PODINFO_UI_MESSAGE // ""')"
if [ "$message" != "scout from the overlay" ]; then
  echo "FAIL: $names has PODINFO_UI_MESSAGE '$message', expected 'scout from the overlay'"
  exit 1
fi

echo "PASS: $names carries the message 'scout from the overlay'"
